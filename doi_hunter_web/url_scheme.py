"""The ``reviewhunter://`` link: any browser, extension or document can start ReviewHunter with it.

    reviewhunter://start              start ReviewHunter in the background (used by the Safari connector,
                                      and by the other connectors when their native helper is missing)
    reviewhunter://open               start it if needed and open the library in the browser
    reviewhunter://open?item=12       ... on paper 12

Browsers ask once before handing the link to the operating system ("Open ReviewHunter?", with an
"always allow" choice), so a web page cannot start it silently; a link can only start or open
ReviewHunter, nothing else.

Registration (per user, no administrator rights; checked at every launch like the shortcuts):
    Windows  HKCU\\Software\\Classes\\reviewhunter  -> <install>/native_host/reviewhunter_url.pyw "%1"
    Linux    ~/.local/share/applications/reviewhunter-url.desktop (x-scheme-handler/reviewhunter)
    macOS    CFBundleURLTypes in ~/Applications/ReviewHunter.app (written by shortcuts.py). A script
             based app does not receive the link text (macOS sends it as an Apple Event), so on macOS
             every reviewhunter:// link simply starts ReviewHunter and opens the library.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Optional
from urllib.parse import parse_qs, urlparse

SCHEME = "reviewhunter"
ROOT = Path(__file__).resolve().parents[1]
IS_WINDOWS = os.name == "nt"
IS_MAC = sys.platform == "darwin"
WINDOWS_KEY = rf"Software\Classes\{SCHEME}"


def parse(url: str) -> dict:
    """reviewhunter://open?item=12 -> {"action": "open", "item": 12}. Unknown links just open the library."""
    try:
        u = urlparse(url or "")
    except ValueError:
        return {"action": "open", "item": None}
    if u.scheme.lower() != SCHEME:
        return {"action": "open", "item": None}
    action = (u.netloc or u.path.strip("/").split("/")[0] or "open").lower()
    item = (parse_qs(u.query).get("item") or [""])[0]
    return {"action": "start" if action == "start" else "open", "item": int(item) if item.isdigit() else None}


def handler_script(root: Path = ROOT) -> Path:
    return Path(root) / "native_host" / "reviewhunter_url.pyw"


def _handler_text(root: Path) -> str:
    return ("# Opens reviewhunter:// links (generated by ReviewHunter, repaired automatically).\n"
            "import os, sys\n"
            f"ROOT = {str(root)!r}\n"
            "os.chdir(ROOT)\nsys.path.insert(0, ROOT)\n"
            "from doi_hunter_web.launcher import main\n"
            "sys.exit(main(['--url', sys.argv[1] if len(sys.argv) > 1 else '']))\n")


def _windows_command(root: Path) -> str:
    from .shortcuts import launcher_python

    return f'"{launcher_python(root)}" "{handler_script(root)}" "%1"'


def _linux_entry_path() -> Path:
    data = Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local" / "share"))
    return data / "applications" / "reviewhunter-url.desktop"


def _linux_entry(root: Path) -> str:
    from .shortcuts import launcher_python

    return ("[Desktop Entry]\nType=Application\nName=ReviewHunter link handler\nNoDisplay=true\n"
            f'Exec="{launcher_python(root)}" "{handler_script(root)}" %u\n'
            f"Path={root}\nMimeType=x-scheme-handler/{SCHEME};\nTerminal=false\n")


def status(root: Path = ROOT, key: str = WINDOWS_KEY) -> dict:
    root = Path(root)
    script_ok = handler_script(root).exists() and handler_script(root).read_text(encoding="utf-8") == _handler_text(root)
    if IS_WINDOWS:
        import winreg

        try:
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, rf"{key}\shell\open\command") as k:
                command = winreg.QueryValueEx(k, "")[0]
        except OSError:
            command = ""
        return {"registered": bool(command), "linked": command == _windows_command(root) and script_ok,
                "where": rf"HKCU\{key}"}
    if IS_MAC:   # declared by the .app bundle; shortcuts.ensure keeps it current
        from . import shortcuts

        bundle = shortcuts.shortcut_path("menu", shortcuts.default_places()["menu"])
        plist = bundle / "Contents" / "Info.plist"
        declared = plist.exists() and f"<string>{SCHEME}</string>" in plist.read_text(encoding="utf-8")
        return {"registered": declared, "linked": declared, "where": str(plist)}
    entry = _linux_entry_path()
    text = entry.read_text(encoding="utf-8") if entry.exists() else ""
    return {"registered": bool(text), "linked": text == _linux_entry(root) and script_ok, "where": str(entry)}


def register(root: Path = ROOT, key: str = WINDOWS_KEY) -> dict:
    from .shortcuts import skip_reason

    root = Path(root).resolve()
    reason = skip_reason(root)
    if reason:
        return {"skipped": reason}
    if status(root, key)["linked"]:
        return {"ok": True, "changed": False, **status(root, key)}
    if IS_MAC:
        return {"ok": True, "changed": False, "note": "declared by ReviewHunter.app", **status(root, key)}
    script = handler_script(root)
    script.parent.mkdir(parents=True, exist_ok=True)
    script.write_text(_handler_text(root), encoding="utf-8")
    if IS_WINDOWS:
        import winreg

        with winreg.CreateKey(winreg.HKEY_CURRENT_USER, key) as k:
            winreg.SetValueEx(k, "", 0, winreg.REG_SZ, "URL:ReviewHunter")
            winreg.SetValueEx(k, "URL Protocol", 0, winreg.REG_SZ, "")
        icon = root / "installer" / "reviewhunter.ico"
        if icon.exists():
            with winreg.CreateKey(winreg.HKEY_CURRENT_USER, rf"{key}\DefaultIcon") as k:
                winreg.SetValueEx(k, "", 0, winreg.REG_SZ, str(icon))
        with winreg.CreateKey(winreg.HKEY_CURRENT_USER, rf"{key}\shell\open\command") as k:
            winreg.SetValueEx(k, "", 0, winreg.REG_SZ, _windows_command(root))
    else:
        entry = _linux_entry_path()
        entry.parent.mkdir(parents=True, exist_ok=True)
        entry.write_text(_linux_entry(root), encoding="utf-8")
        if shutil.which("xdg-mime"):
            subprocess.run(["xdg-mime", "default", entry.name, f"x-scheme-handler/{SCHEME}"], capture_output=True)
        if shutil.which("update-desktop-database"):
            subprocess.run(["update-desktop-database", str(entry.parent)], capture_output=True)
    return {"ok": True, "changed": True, **status(root, key)}


def unregister(root: Path = ROOT, key: str = WINDOWS_KEY) -> bool:
    if IS_WINDOWS:
        import winreg

        def delete_tree(path: str) -> None:
            try:
                with winreg.OpenKey(winreg.HKEY_CURRENT_USER, path) as k:
                    while True:
                        try:
                            delete_tree(rf"{path}\{winreg.EnumKey(k, 0)}")
                        except OSError:
                            break
                winreg.DeleteKey(winreg.HKEY_CURRENT_USER, path)
            except OSError:
                pass

        delete_tree(key)
        return not status(root, key)["registered"]
    if not IS_MAC:
        _linux_entry_path().unlink(missing_ok=True)
    return True
