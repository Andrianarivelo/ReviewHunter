<#
.SYNOPSIS
    Installs (or removes) the ReviewHunter add-in for Microsoft Word on this Windows account.

.DESCRIPTION
    ReviewHunter serves its Word add-in from https://localhost. Word only loads add-ins
    over HTTPS it trusts, and only lists add-ins it knows about. This script therefore:

      1. trusts the local "ReviewHunter Local CA" certificate for YOUR Windows account
         (Cert:\CurrentUser\Root). Windows shows its own security warning: that is expected.
      2. registers the add-in manifest for Word (HKCU\Software\Microsoft\Office\16.0\WEF\Developer).
      3. optionally clears Word's add-in cache so Word reloads the add-in files.

    Nothing is changed for other Windows users and no administrator rights are needed.
    ReviewHunter itself launches this script with the right paths
    (Word add-in setup button). You can also double-click scripts\setup_word_addin.cmd.

.PARAMETER CaCert
    Path to reviewhunter-ca.crt (generated by ReviewHunter in <library>\certs).

.PARAMETER Manifest
    Path to manifest.xml (generated by ReviewHunter in <library>\word_addin).

.PARAMETER AddinId
    Manifest GUID, used as the registry value name.

.PARAMETER Uninstall
    Remove the registration and the certificate instead of installing them.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File setup_word_addin.ps1 -CaCert C:\Users\me\ReviewHunter\certs\reviewhunter-ca.crt -Manifest C:\Users\me\ReviewHunter\word_addin\manifest.xml

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File setup_word_addin.ps1 -Uninstall
#>
[CmdletBinding()]
param(
    [string]$CaCert = "",
    [string]$Manifest = "",
    [string]$AddinId = "6f1f2a57-4c1b-4a0e-9d6e-7e0c5b1a9a01",
    [switch]$Uninstall,
    [switch]$Quiet
)

# ------------------------------------------------------------------ configuration
$ErrorActionPreference = "Stop"
$CaSubject   = "CN=ReviewHunter Local CA"                               # subject of the local CA
$DevKey      = "HKCU:\Software\Microsoft\Office\16.0\WEF\Developer"      # Word sideloading key
$WefCache    = Join-Path $env:LOCALAPPDATA "Microsoft\Office\16.0\Wef"   # Office add-in cache
$LibraryRoot = if ($env:REVIEWHUNTER_HOME) { $env:REVIEWHUNTER_HOME } else { Join-Path $env:USERPROFILE "ReviewHunter" }

# ------------------------------------------------------------------ helpers

function Write-Title([string]$Text) {
    <# Section header in cyan. #>
    Write-Host ""
    Write-Host "== $Text" -ForegroundColor Cyan
}

function Write-Info([string]$Text) {
    <# Plain explanation line. #>
    Write-Host "   $Text"
}

function Write-Ok([string]$Text) {
    <# Success line in green. #>
    Write-Host "   [ok] $Text" -ForegroundColor Green
}

function Write-Warn([string]$Text) {
    <# Warning line in yellow. #>
    Write-Host "   [!] $Text" -ForegroundColor Yellow
}

function Resolve-DefaultPath([string]$Given, [string]$Default) {
    <# Use the given path, else the default location in the ReviewHunter library. #>
    if ($Given) { return $Given }
    return $Default
}

function Get-CertThumbprint([string]$Path) {
    <# SHA-1 thumbprint of a PEM or DER certificate file (the store is indexed by it). #>
    $cert = New-Object System.Security.Cryptography.X509Certificates.X509Certificate2 -ArgumentList $Path
    return $cert.Thumbprint.ToUpperInvariant()
}

function Test-WordRunning {
    <# True when a Word process is running for this user. #>
    return [bool](Get-Process -Name WINWORD -ErrorAction SilentlyContinue)
}

function Clear-OfficeAddinCache {
    <# Offer to delete Office's cached add-in files (only when Word is closed). #>
    Write-Title "Step 3 - Office add-in cache (optional)"
    Write-Info "Word keeps a copy of add-in files. Clearing it makes Word load the newest ReviewHunter pane."
    if (-not (Test-Path $WefCache)) {
        Write-Ok "No cache folder found, nothing to clear."
        return
    }
    if (Test-WordRunning) {
        Write-Warn "Word is running, so the cache is left untouched. Close Word and run this script again to clear it."
        return
    }
    # -Quiet (the "ReviewHunter for Word" shortcut): no question; the cache only holds copies, so clear it.
    $answer = if ($Quiet) { "y" } else { Read-Host "   Clear the Office add-in cache now? This only removes cached copies (Y/N)" }
    if ($answer -match '^(y|yes|o|oui)$') {
        Get-ChildItem -LiteralPath $WefCache -Force | Remove-Item -Recurse -Force -ErrorAction SilentlyContinue
        Write-Ok "Cache cleared ($WefCache)."
    } else {
        Write-Info "Cache kept."
    }
}

# ------------------------------------------------------------------ uninstall

function Invoke-Uninstall {
    <# Remove the manifest registration and the trusted certificate. #>
    Write-Host ""
    Write-Host "ReviewHunter Word add-in: removal" -ForegroundColor White

    Write-Title "Step 1 - Unregister the add-in"
    if ((Test-Path $DevKey) -and ($null -ne (Get-ItemProperty -Path $DevKey -Name $AddinId -ErrorAction SilentlyContinue))) {
        Remove-ItemProperty -Path $DevKey -Name $AddinId
        Write-Ok "Word will no longer list ReviewHunter."
    } else {
        Write-Ok "The add-in was not registered."
    }

    Write-Title "Step 2 - Remove the trusted certificate"
    Write-Info "Windows may ask you to confirm deleting the certificate: answer Yes."
    $thumbs = @()
    $certPath = Resolve-DefaultPath $CaCert (Join-Path $LibraryRoot "certs\reviewhunter-ca.crt")
    if (Test-Path $certPath) { $thumbs += Get-CertThumbprint $certPath }
    # Also catch older ReviewHunter CAs (for example after the certificate was regenerated).
    $thumbs += Get-ChildItem Cert:\CurrentUser\Root | Where-Object { $_.Subject -like "*$CaSubject*" } | ForEach-Object { $_.Thumbprint }
    $thumbs = $thumbs | Where-Object { $_ } | Select-Object -Unique
    if (-not $thumbs) {
        Write-Ok "No ReviewHunter certificate is trusted."
    }
    foreach ($t in $thumbs) {
        $item = "Cert:\CurrentUser\Root\$t"
        if (Test-Path $item) {
            try {
                Remove-Item -Path $item
                Write-Ok "Removed certificate $t."
            } catch {
                Write-Warn "Certificate $t was not removed ($($_.Exception.Message))."
            }
        }
    }

    Clear-OfficeAddinCache
    Write-Title "Done"
    Write-Info "Restart Word to finish. ReviewHunter citations already in documents stay as they are."
}

# ------------------------------------------------------------------ install

function Invoke-Install {
    <# Trust the CA, register the manifest, optionally clear the cache, explain what is next. #>
    Write-Host ""
    Write-Host "ReviewHunter Word add-in: setup" -ForegroundColor White
    Write-Info "This connects Microsoft Word to the ReviewHunter app running on this computer."
    Write-Info "Only your Windows account is affected. Run it again with -Uninstall to undo everything."

    $script:CaCert = Resolve-DefaultPath $CaCert (Join-Path $LibraryRoot "certs\reviewhunter-ca.crt")
    $script:Manifest = Resolve-DefaultPath $Manifest (Join-Path $LibraryRoot "word_addin\manifest.xml")
    foreach ($pair in @(@("certificate", $CaCert), @("manifest", $Manifest))) {
        if (-not (Test-Path -LiteralPath $pair[1])) {
            Write-Warn "The $($pair[0]) file was not found: $($pair[1])"
            Write-Info "Start ReviewHunter once (it creates both files), then run the Word add-in setup from ReviewHunter (or this script) again."
            exit 1
        }
    }
    $Manifest = (Resolve-Path -LiteralPath $Manifest).Path

    # Step 1: certificate
    Write-Title "Step 1 - Trust the local ReviewHunter certificate"
    Write-Info "Word refuses add-ins served over HTTPS it does not trust. ReviewHunter created a private"
    Write-Info "certificate authority that is only used for https://localhost on this computer."
    $thumb = Get-CertThumbprint $CaCert
    if (Test-Path "Cert:\CurrentUser\Root\$thumb") {
        Write-Ok "Already trusted (thumbprint $thumb)."
    } else {
        Write-Info "Windows will now show a Security Warning about installing a certificate"
        Write-Info "named 'ReviewHunter Local CA'. Check the thumbprint below and click Yes."
        Write-Info "Thumbprint: $thumb"
        try {
            Import-Certificate -FilePath $CaCert -CertStoreLocation Cert:\CurrentUser\Root | Out-Null
        } catch {
            Write-Warn "The certificate was not installed: $($_.Exception.Message)"
        }
        if (Test-Path "Cert:\CurrentUser\Root\$thumb") {
            Write-Ok "Certificate trusted."
        } else {
            Write-Warn "The certificate is not trusted (the Windows dialog was probably declined)."
            Write-Info "Word will show a blank or error pane until it is trusted. Run this script again to retry."
        }
    }

    # Step 2: manifest registration
    Write-Title "Step 2 - Register the add-in with Word"
    Write-Info "Word reads developer add-in manifests listed under $DevKey"
    if (-not (Test-Path $DevKey)) {
        New-Item -Path $DevKey -Force | Out-Null
    }
    New-ItemProperty -Path $DevKey -Name $AddinId -Value $Manifest -PropertyType String -Force | Out-Null
    Write-Ok "Registered $Manifest"

    # Step 3: cache
    Clear-OfficeAddinCache

    # Next steps
    Write-Title "Next steps"
    if (Test-WordRunning) {
        Write-Warn "Word is open: close every Word window, then start Word again."
    } else {
        Write-Info "Start Word."
    }
    Write-Info "Keep ReviewHunter running, open a document, then click References > ReviewHunter."
    Write-Info "If the button is missing, use Home > Add-ins (or Insert > My Add-ins) > Developer Add-ins > ReviewHunter."
    Write-Info "The pane shows 'Online' when it can reach your library."
    Write-Host ""
    if ($Quiet) {
        # One-click install: the console is hidden, so finish with a plain dialog.
        $trusted = Test-Path "Cert:\CurrentUser\Root\$thumb"
        $restart = if (Test-WordRunning) { "Close every Word window and start Word again." } else { "Start Word." }
        $text = if ($trusted) {
            "ReviewHunter is now available in Word.`n`n$restart Then open a document and click References > ReviewHunter.`n`nKeep ReviewHunter running while you cite."
        } else {
            "Word is registered, but the ReviewHunter certificate was not accepted, so Word cannot open the pane.`n`nRun 'ReviewHunter for Word' again and click Yes in the Windows security warning."
        }
        Add-Type -AssemblyName System.Windows.Forms
        [System.Windows.Forms.MessageBox]::Show($text, "ReviewHunter for Word", "OK",
            $(if ($trusted) { "Information" } else { "Warning" })) | Out-Null
    }
}

# ------------------------------------------------------------------ main
try {
    if ($Uninstall) { Invoke-Uninstall } else { Invoke-Install }
} catch {
    Write-Host ""
    Write-Host "Setup stopped: $($_.Exception.Message)" -ForegroundColor Red
    exit 1
}
